function getPreferredTheme() {
    const storedTheme = localStorage.getItem('portfolio-theme');
    if (storedTheme === 'dark' || storedTheme === 'light') {
        return storedTheme;
    }

    return window.matchMedia && window.matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark';
}

function getPreferredLanguage() {
    const storedLanguage = localStorage.getItem('portfolio-lang');
    if (storedLanguage === 'tr' || storedLanguage === 'en') {
        return storedLanguage;
    }

    return 'tr';
}

function applyTheme(theme) {
    document.documentElement.dataset.theme = theme;
    localStorage.setItem('portfolio-theme', theme);

    const activeLanguage = document.documentElement.lang === 'en' ? 'en' : 'tr';
    themeToggle.innerHTML = theme === 'dark' ? themeIcon.dark : themeIcon.light;
    themeToggle.title = theme === 'dark' ? translations[activeLanguage]['theme.titleDark'] : translations[activeLanguage]['theme.titleLight'];
    themeToggle.setAttribute('aria-label', themeToggle.title);
}

function applyLanguage(language) {
    document.documentElement.lang = language;
    localStorage.setItem('portfolio-lang', language);

    document.querySelectorAll('[data-i18n]').forEach((node) => {
        const key = node.getAttribute('data-i18n');
        const value = translations[language][key];
        if (value) {
            node.textContent = value;
        }
    });

    langToggle.textContent = language === 'tr' ? 'EN' : 'TR';
    langToggle.title = language === 'tr' ? 'Switch to English' : 'Türkçeye geç';
    langToggle.setAttribute('aria-label', langToggle.title);

    const theme = document.documentElement.dataset.theme || 'dark';
    applyTheme(theme);
}

function setActiveNavLink(id) {
    navLinks.forEach((link) => {
        link.classList.toggle('is-active', link.getAttribute('href') === `#${id}`);
    });
}

function initSectionTracking() {
    if (!('IntersectionObserver' in window)) {
        return;
    }

    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                setActiveNavLink(entry.target.id);
            }
        });
    }, {
        root: null,
        rootMargin: '-45% 0px -48% 0px',
        threshold: 0.01
    });

    sections.forEach((section) => observer.observe(section));

    // Scroll Reveal Observer
    const revealObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('is-visible');
                // Optional: unobserve if we only want it to reveal once
                // revealObserver.unobserve(entry.target);
            }
        });
    }, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });

    document.querySelectorAll('.reveal-up').forEach(el => revealObserver.observe(el));
}

function initAnchorScrolling() {
    document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
        anchor.addEventListener('click', (event) => {
            const targetId = anchor.getAttribute('href');
            if (!targetId || targetId === '#') {
                return;
            }

            const target = document.querySelector(targetId);
            if (!target) {
                return;
            }

            event.preventDefault();
            target.scrollIntoView({ behavior: 'auto', block: 'start' });
        });
    });
}

function ensureLightbox() {
    if (lightboxElements) {
        return lightboxElements;
    }

    const overlay = document.createElement('div');
    overlay.className = 'lightbox';
    overlay.setAttribute('aria-hidden', 'true');

    overlay.innerHTML = `
        <div class="lightbox-panel" role="dialog" aria-modal="true" aria-label="Model görseli">
            <div class="lightbox-caption">
                <span class="lightbox-title"></span>
                <button type="button" class="lightbox-close" aria-label="Kapat">X</button>
            </div>
            <div class="lightbox-image-wrap">
                <img class="lightbox-image" alt="">
            </div>
        </div>
    `;

    document.body.appendChild(overlay);

    const title = overlay.querySelector('.lightbox-title');
    const image = overlay.querySelector('.lightbox-image');
    const closeButton = overlay.querySelector('.lightbox-close');

    const closeLightbox = () => {
        overlay.classList.remove('is-open');
        overlay.setAttribute('aria-hidden', 'true');
        document.body.classList.remove('has-lightbox-open');
    };

    overlay.addEventListener('click', (event) => {
        if (event.target === overlay) {
            closeLightbox();
        }
    });

    closeButton.addEventListener('click', closeLightbox);

    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape' && overlay.classList.contains('is-open')) {
            closeLightbox();
        }
    });

    lightboxElements = {
        overlay,
        image,
        title,
        open(sourceImage) {
            const caption = sourceImage.alt || sourceImage.closest('.media-card')?.querySelector('h3')?.textContent || 'Model görseli';
            image.src = sourceImage.src;
            image.alt = caption;
            title.textContent = caption;
            overlay.classList.add('is-open');
            overlay.setAttribute('aria-hidden', 'false');
            document.body.classList.add('has-lightbox-open');
            closeButton.focus();
        }
    };

    return lightboxElements;
}

function initModelLightbox() {
    modelImages = getModelImages();
    if (!modelImages.length) {
        return;
    }

    const lightbox = ensureLightbox();

    modelImages.forEach((image) => {
        const frame = image.closest('.media-frame');
        if (!frame || frame.dataset.boundLightbox) {
            return;
        }

        frame.dataset.boundLightbox = 'true';
        frame.classList.add('is-zoomable');
        frame.setAttribute('role', 'button');
        frame.setAttribute('tabindex', '0');
        frame.setAttribute('aria-label', `${image.alt} görselini büyüt`);

        const openFromImage = () => lightbox.open(image);

        frame.addEventListener('click', openFromImage);
        frame.addEventListener('keydown', (event) => {
            if (event.key === 'Enter' || event.key === ' ') {
                event.preventDefault();
                openFromImage();
            }
        });
    });
}

function applyStickyStatusPanel() {
    if (!statusPanel) {
        return;
    }

    if (window.innerWidth > 980) {
        statusPanel.style.position = 'sticky';
        statusPanel.style.top = '92px';
        statusPanel.style.alignSelf = 'start';
        statusPanel.style.maxHeight = 'calc(100vh - 110px)';
        statusPanel.style.overflow = 'auto';
    } else {
        statusPanel.style.position = '';
        statusPanel.style.top = '';
        statusPanel.style.alignSelf = '';
        statusPanel.style.maxHeight = '';
        statusPanel.style.overflow = '';
    }
}

function initCustomCursor() {
    // Create cursor elements
    const cursorDot = document.createElement('div');
    cursorDot.className = 'custom-cursor-dot';

    const cursorGlow = document.createElement('div');
    cursorGlow.className = 'custom-cursor-glow';

    document.body.appendChild(cursorDot);
    document.body.appendChild(cursorGlow);

    // Track mouse movement
    document.addEventListener('mousemove', (e) => {
        const { clientX: x, clientY: y } = e;

        // Dot moves instantly
        cursorDot.style.left = `${x}px`;
        cursorDot.style.top = `${y}px`;

        // Glow moves with slight delay
        cursorGlow.style.left = `${x}px`;
        cursorGlow.style.top = `${y}px`;
    });

    // Hover effect on interactive elements
    const interactables = document.querySelectorAll('a, button, .is-zoomable, .social-circle, .nav-link');
    interactables.forEach(el => {
        el.addEventListener('mouseenter', () => {
            document.body.classList.add('cursor-hover');
        });
        el.addEventListener('mouseleave', () => {
            document.body.classList.remove('cursor-hover');
        });
    });
}

function initControls() {
    themeToggle.addEventListener('click', () => {
        const nextTheme = document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark';
        applyTheme(nextTheme);
    });

    langToggle.addEventListener('click', () => {
        const nextLanguage = document.documentElement.lang === 'en' ? 'tr' : 'en';
        applyLanguage(nextLanguage);
    });
}

document.addEventListener('DOMContentLoaded', () => {
    const initialTheme = getPreferredTheme();
    const initialLanguage = getPreferredLanguage();

    applyTheme(initialTheme);
    applyLanguage(initialLanguage);
    initControls();
    initAnchorScrolling();
    initSectionTracking();
    initModelLightbox();
    initCustomCursor();
    init3DTiltEffect();

    // Setup Modal Logic
    const showMoreBtn = document.getElementById('show-more-models-btn');
    const allModelsModal = document.getElementById('all-models-modal');
    const closeAllModelsBtn = document.getElementById('close-all-models-btn');

    if (showMoreBtn && allModelsModal && closeAllModelsBtn) {
        showMoreBtn.addEventListener('click', () => {
            allModelsModal.classList.add('is-open');
            allModelsModal.setAttribute('aria-hidden', 'false');
            document.body.classList.add('has-lightbox-open'); // reuse overflow hidden
            initModelLightbox(); // re-bind just in case
        });

        closeAllModelsBtn.addEventListener('click', () => {
            allModelsModal.classList.remove('is-open');
            allModelsModal.setAttribute('aria-hidden', 'true');
            document.body.classList.remove('has-lightbox-open');
        });

        // Close modal on escape
        document.addEventListener('keydown', (event) => {
            if (event.key === 'Escape' && allModelsModal.classList.contains('is-open') && (!lightboxElements || !lightboxElements.overlay.classList.contains('is-open'))) {
                allModelsModal.classList.remove('is-open');
                allModelsModal.setAttribute('aria-hidden', 'true');
                document.body.classList.remove('has-lightbox-open');
            }
        });

        // Close modal on outside click
        allModelsModal.addEventListener('click', (event) => {
            if (event.target === allModelsModal) {
                allModelsModal.classList.remove('is-open');
                allModelsModal.setAttribute('aria-hidden', 'true');
                document.body.classList.remove('has-lightbox-open');
            }
        });
    }
});

function init3DTiltEffect() {
    const tiltElements = document.querySelectorAll('.media-card, .project-card');

    tiltElements.forEach(el => {
        el.addEventListener('mouseenter', () => {
            el.style.transition = 'transform 0.3s cubic-bezier(0.25, 0.46, 0.45, 0.94), box-shadow 0.3s ease';
        });

        el.addEventListener('mousemove', (e) => {
            if (window.matchMedia("(pointer: coarse)").matches) return;

            const rect = el.getBoundingClientRect();
            const x = e.clientX - rect.left;
            const y = e.clientY - rect.top;

            const centerX = rect.width / 2;
            const centerY = rect.height / 2;

            const rotateX = ((y - centerY) / centerY) * -4;
            const rotateY = ((x - centerX) / centerX) * 4;

            el.style.transform = `perspective(1200px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) scale3d(1.01, 1.01, 1.01)`;
            el.style.zIndex = '10';

            const shadowX = (centerX - x) / 20;
            const shadowY = (centerY - y) / 20;
            el.style.boxShadow = `${shadowX}px ${shadowY}px 25px color-mix(in srgb, var(--accent) 20%, transparent)`;
        });

        el.addEventListener('mouseleave', () => {
            el.style.transition = 'transform 0.8s cubic-bezier(0.25, 1, 0.5, 1), box-shadow 0.8s ease';
            el.style.transform = 'perspective(1200px) rotateX(0) rotateY(0) scale3d(1, 1, 1)';
            el.style.zIndex = '1';
            el.style.boxShadow = '';
        });
    });
}


